str_list *string_split(char *str, char delimiter) {
  str_list *result = list_init();
  char *copy = strdup(str);
  char delim[2] = {delimiter, '\0'};
  char *token = strtok(copy, delim);
  while (token != NULL) {
    list_append(result, strdup(token));
    token = strtok(NULL, delim);
  }
  free(copy);
  return result;
}

char *string_remove_linefeed(char *str) {
  char *newstr = strdup(str);
  size_t len = strlen(newstr);
  if (len > 0 && newstr[len - 1] == '\n')
    newstr[len - 1] = '\0';
  return newstr;
}

char *string_replace(char *str, char old_char, char new_char) {
  char *newstr = strdup(str);
  for (size_t i = 0; i < strlen(newstr); i++)
    if (newstr[i] == old_char)
      newstr[i] = new_char;
  return newstr;
}

char *gen_random_string(size_t length) {
  char *s = malloc(length + 1);
  for (uint8_t i = 0; i < length; i++) {
    s[i] = 'A' + get_rand_32() % 26;
  }
  s[length] = '\0';
  return s;
}

char *
string_substring_replace(const char *str, const char *old, const char *new) {
  size_t str_len = strlen(str);
  size_t old_len = strlen(old);
  size_t new_len = strlen(new);
  if (old_len == 0)
    return NULL;
  size_t count = 0;
  const char *p = str;
  while ((p = strstr(p, old)) != NULL) {
    count++;
    p += old_len;
  }
  size_t new_str_len = str_len + count * (new_len - old_len) + 1;
  char *result = malloc(new_str_len);
  if (!result)
    return NULL;
  char *dst = result;
  p = str;
  const char *match;
  while ((match = strstr(p, old)) != NULL) {
    size_t bytes_before = match - p;
    memcpy(dst, p, bytes_before);
    dst += bytes_before;
    memcpy(dst, new, new_len);
    dst += new_len;
    p = match + old_len;
  }
  strcpy(dst, p);
  return result;
}
