collector *collector_inst;

void collector_init() {
  collector_inst = (collector *)malloc(sizeof(collector));
  collector_inst->count = 0;
  for (uint8_t i = 0; i < COLLECTOR_MAX_STR; i++) {
    collector_inst->pointers[i] = NULL;
  }
}

void collector_add(char *str) {
  if (collector_inst->count >= COLLECTOR_MAX_STR) {
    printf("!!! Collector is full !!!\n");
    return;
  }
  collector_inst->pointers[collector_inst->count] = str;
  collector_inst->count++;
}

/**
 * @brief Frees all strings that were generated by string_add()
 * this is to make possible the nested usage of string_add() without
 * keeping pointers
 */
void collect() {
  for (uint8_t i = 0; i < collector_inst->count; i++) {
    if (collector_inst->pointers[i] != NULL) {
      free(collector_inst->pointers[i]);
      collector_inst->pointers[i] = NULL;
    }
  }
  collector_inst->count = 0;
}

/**
 * @brief Concatenates two strings.
 * It is not necessary to keep the returned pointer to later free it as it is
 * automatically added to the collector, you can call collect() to free
 * all the strings that were generated by string_add().
 * This allows for nested and clean usage of string_add().
 *
 * @param str1 The first string.
 * @param str2 The second string.
 * @return A new string that is the concatenation of str1 and str2, or NULL on
 * failure.
 */
char *string_add(char *str1, char *str2) {
  size_t len1 = strlen(str1);
  size_t len2 = strlen(str2);
  char *result = malloc(len1 + len2 + 1);
  if (!result)
    return NULL;
  for (size_t i = 0; i < len1; ++i)
    result[i] = str1[i];
  for (size_t i = 0; i < len2; ++i)
    result[len1 + i] = str2[i];
  result[len1 + len2] = '\0';
  collector_add(result);
  return result;
}

uint16_t array_find_max(uint16_t *array, size_t len) {
  uint16_t max = 0;
  for (uint8_t i = 0; i < len; i++)
    if (array[i] > max)
      max = array[i];
  return max;
}

uint16_t array_find_min(uint16_t *array, size_t len) {
  uint16_t min = array[0];
  for (uint8_t i = 0; i < len; i++)
    if (array[i] < min)
      min = array[i];
  return min;
}

bool is_string_numeric(char *str) {
  for (uint8_t i = 0; i < strlen(str); i++)
    if (str[i] < '0' || str[i] > '9')
      return false;
  return true;
}

bool is_string_alphanumeric(char *str) {
  for (uint8_t i = 0; i < strlen(str); i++)
    if ((str[i] < '0' || str[i] > '9') && (str[i] < 'A' || str[i] > 'Z') &&
        (str[i] < 'a' || str[i] > 'z'))
      return false;
  return true;
}

bool is_string_alpha(char *str) {
  for (uint8_t i = 0; i < strlen(str); i++)
    if ((str[i] < 'A' || str[i] > 'Z') && (str[i] < 'a' || str[i] > 'z'))
      return false;
  return true;
}

